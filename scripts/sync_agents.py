"""Render canonical `.agent/agents/*.md` specs into platform-native sub-agent files.

Single source of truth:
    .agent/models.yaml           model/reasoning profiles + abstract tool -> platform tool map
    .agent/agents/<name>.md      canonical agent spec (platform-neutral frontmatter + body)
    .agent/agents/_shared/*.md   protocol appended to every rendered agent

Generated (committed, never hand-edited):
    .claude/agents/<name>.md     Claude Code sub-agents
    .gemini/agents/<name>.md     Gemini CLI sub-agents
    .gemini/settings.json        `agents.overrides.<name>.modelConfig` thinkingConfig (merged;
                                 unrelated user settings are preserved)

Usage:
    uv run --no-sync python scripts/sync_agents.py          # write adapters
    uv run --no-sync python scripts/sync_agents.py --check  # exit 1 if adapters are stale
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
AGENT_DIR = ROOT / ".agent" / "agents"
SHARED_DIR = AGENT_DIR / "_shared"
MODELS_FILE = ROOT / ".agent" / "models.yaml"
PLATFORMS: dict[str, Path] = {
    "claude": ROOT / ".claude" / "agents",
    "gemini": ROOT / ".gemini" / "agents",
}
GEMINI_SETTINGS = ROOT / ".gemini" / "settings.json"
REQUIRED_KEYS: tuple[str, ...] = ("name", "description", "profile", "tools", "owns", "forbidden")
NAME_RE = re.compile(r"^[a-z][a-z0-9-]{1,48}$")
FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z", re.DOTALL)
GENERATED_NOTE = (
    "<!-- GENERATED by scripts/sync_agents.py from .agent/agents/{name}.md — "
    "do not edit; run `make agents-sync`. -->"
)


class AgentSpecError(ValueError):
    """Raised when a canonical agent spec or models.yaml is invalid."""


@dataclass(frozen=True)
class AgentSpec:
    name: str
    description: str
    profile: str
    tools: tuple[str, ...]
    owns: tuple[str, ...]
    reads: tuple[str, ...]
    forbidden: tuple[str, ...]
    color: str | None
    body: str
    source: Path


def _as_str_tuple(value: Any, key: str, source: Path) -> tuple[str, ...]:
    if value is None:
        return ()
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise AgentSpecError(f"{source.name}: '{key}' must be a list of strings")
    return tuple(value)


def load_models(path: Path = MODELS_FILE) -> dict[str, Any]:
    data: Any = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or "profiles" not in data or "tools" not in data:
        raise AgentSpecError(f"{path}: must define 'profiles' and 'tools'")
    for pname, prof in data["profiles"].items():
        for platform in PLATFORMS:
            if not isinstance(prof, dict) or "model" not in prof.get(platform, {}):
                raise AgentSpecError(f"profile '{pname}' missing {platform}.model")
    return data


def parse_agent(path: Path) -> AgentSpec:
    match = FRONTMATTER_RE.match(path.read_text(encoding="utf-8"))
    if not match:
        raise AgentSpecError(f"{path.name}: missing YAML frontmatter")
    meta: Any = yaml.safe_load(match.group(1))
    if not isinstance(meta, dict):
        raise AgentSpecError(f"{path.name}: frontmatter must be a mapping")
    missing = [k for k in REQUIRED_KEYS if k not in meta]
    if missing:
        raise AgentSpecError(f"{path.name}: missing keys {missing}")
    name = str(meta["name"])
    if not NAME_RE.match(name) or path.stem != name:
        raise AgentSpecError(f"{path.name}: name '{name}' must be kebab-case and match filename")
    color = meta.get("color")
    return AgentSpec(
        name=name,
        description=" ".join(str(meta["description"]).split()),
        profile=str(meta["profile"]),
        tools=_as_str_tuple(meta["tools"], "tools", path),
        owns=_as_str_tuple(meta["owns"], "owns", path),
        reads=_as_str_tuple(meta.get("reads"), "reads", path),
        forbidden=_as_str_tuple(meta["forbidden"], "forbidden", path),
        color=str(color) if color is not None else None,
        body=match.group(2).strip(),
        source=path,
    )


def load_agents(agent_dir: Path = AGENT_DIR) -> list[AgentSpec]:
    paths = sorted(p for p in agent_dir.glob("*.md") if p.name.lower() != "readme.md")
    return [parse_agent(p) for p in paths]


def validate(agents: list[AgentSpec], models: dict[str, Any]) -> None:
    tool_map: dict[str, Any] = models["tools"]
    for agent in agents:
        if agent.profile not in models["profiles"]:
            raise AgentSpecError(f"{agent.name}: unknown profile '{agent.profile}'")
        unknown = [t for t in agent.tools if t not in tool_map]
        if unknown:
            raise AgentSpecError(f"{agent.name}: unknown tools {unknown}")


def _shared_protocol() -> str:
    parts = [p.read_text(encoding="utf-8").strip() for p in sorted(SHARED_DIR.glob("*.md"))]
    return "\n\n".join(parts)


def _bullets(items: tuple[str, ...]) -> str:
    return "\n".join(f"- `{i}`" if " " not in i else f"- {i}" for i in items) or "- (none)"


def _effort(prof: dict[str, Any], platform: str) -> tuple[str, str]:
    """Return (effort label, model/thinking detail) for the given platform."""
    plat: dict[str, Any] = prof[platform]
    thinking: dict[str, Any] = plat.get("thinking_config") or {}
    if platform == "gemini" and thinking:
        cfg = ", ".join(f"{k}={v}" for k, v in thinking.items())
        level = str(thinking.get("thinkingLevel", prof.get("reasoning", "medium"))).lower()
        return level, f"Model `{plat['model']}`, thinking `{cfg}`."
    return str(prof.get("reasoning", "medium")), f"Model `{plat['model']}`."


def render_body(agent: AgentSpec, models: dict[str, Any], shared: str, platform: str) -> str:
    prof: dict[str, Any] = models["profiles"][agent.profile]
    guidance = " ".join(str(prof.get("reasoning_guidance", "")).split())
    effort, detail = _effort(prof, platform)
    scope = (
        "## Scope (Context Diet)\n\n"
        f"**Owns (may edit):**\n{_bullets(agent.owns)}\n\n"
        f"**Reads (context diet — nothing else on startup):**\n{_bullets(agent.reads)}\n\n"
        f"**Forbidden:**\n{_bullets(agent.forbidden)}\n\n"
        f"## Reasoning Mode: `{agent.profile}` (effort: {effort})\n\n"
        f"{detail} {guidance}"
    )
    return f"{agent.body}\n\n{scope}\n\n{shared}\n"


def _frontmatter(data: dict[str, Any]) -> str:
    dumped = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=10_000)
    return f"---\n{dumped}---\n"


def render_claude(agent: AgentSpec, models: dict[str, Any], shared: str) -> str:
    tool_map: dict[str, Any] = models["tools"]
    fm: dict[str, Any] = {
        "name": agent.name,
        "description": agent.description,
        "tools": ", ".join(str(tool_map[t]["claude"]) for t in agent.tools),
        "model": models["profiles"][agent.profile]["claude"]["model"],
    }
    if agent.color:
        fm["color"] = agent.color
    note = GENERATED_NOTE.format(name=agent.name)
    return f"{_frontmatter(fm)}\n{note}\n\n{render_body(agent, models, shared, 'claude')}"


def render_gemini(agent: AgentSpec, models: dict[str, Any], shared: str) -> str:
    tool_map: dict[str, Any] = models["tools"]
    gem: dict[str, Any] = models["profiles"][agent.profile]["gemini"]
    fm: dict[str, Any] = {
        "name": agent.name,
        "description": agent.description,
        "kind": "local",
        "tools": [str(tool_map[t]["gemini"]) for t in agent.tools],
        "model": gem["model"],
    }
    for key in ("temperature", "max_turns", "timeout_mins"):
        if key in gem:
            fm[key] = gem[key]
    note = GENERATED_NOTE.format(name=agent.name)
    return f"{_frontmatter(fm)}\n{note}\n\n{render_body(agent, models, shared, 'gemini')}"


def render_gemini_settings(
    agents: list[AgentSpec], models: dict[str, Any], existing: dict[str, Any]
) -> str:
    """Merge per-agent thinkingConfig into Gemini settings (`agents.overrides.<name>.modelConfig`).

    Gemini agent frontmatter is schema-strict and cannot carry thinking settings, so reasoning
    effort is applied via settings overrides, which Gemini CLI deep-merges into the agent's
    runtime model config (sub-agents do not inherit the chat default thinking level).
    """
    settings = copy.deepcopy(existing)
    overrides: dict[str, Any] = settings.setdefault("agents", {}).setdefault("overrides", {})
    for agent in agents:
        gem: dict[str, Any] = models["profiles"][agent.profile]["gemini"]
        entry: dict[str, Any] = overrides.setdefault(agent.name, {})
        thinking = gem.get("thinking_config")
        if thinking:
            entry["modelConfig"] = {"generateContentConfig": {"thinkingConfig": dict(thinking)}}
        else:
            entry.pop("modelConfig", None)
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


def _load_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    data: Any = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise AgentSpecError(f"{path}: must contain a JSON object")
    return data


def render_all(
    agents: list[AgentSpec] | None = None, models: dict[str, Any] | None = None
) -> dict[Path, str]:
    models = load_models() if models is None else models
    agents = load_agents() if agents is None else agents
    validate(agents, models)
    shared = _shared_protocol()
    out: dict[Path, str] = {}
    for agent in agents:
        out[PLATFORMS["claude"] / f"{agent.name}.md"] = render_claude(agent, models, shared)
        out[PLATFORMS["gemini"] / f"{agent.name}.md"] = render_gemini(agent, models, shared)
    out[GEMINI_SETTINGS] = render_gemini_settings(agents, models, _load_json(GEMINI_SETTINGS))
    return out


def stale_files(rendered: dict[Path, str]) -> list[Path]:
    """Return generated paths whose content differs, plus orphaned *generated* files.

    Hand-written agents placed in `.claude/agents/` or `.gemini/agents/` (no GENERATED marker)
    are left untouched.
    """
    stale = [
        p
        for p, content in rendered.items()
        if not p.exists() or p.read_text(encoding="utf-8") != content
    ]
    for out_dir in PLATFORMS.values():
        if out_dir.exists():
            stale.extend(
                p
                for p in sorted(out_dir.glob("*.md"))
                if p not in rendered
                and "GENERATED by scripts/sync_agents.py" in p.read_text("utf-8")
            )
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if adapters are stale")
    args = parser.parse_args(argv)
    try:
        rendered = render_all()
    except AgentSpecError as exc:
        print(f"AGENT SPEC ERROR: {exc}", file=sys.stderr)
        return 2
    stale = stale_files(rendered)
    if args.check:
        if stale:
            rel = "\n  ".join(str(p.relative_to(ROOT)) for p in stale)
            print(f"Agent adapters out of sync (run `make agents-sync`):\n  {rel}", file=sys.stderr)
            return 1
        print(f"Agent Specs Sync: PASS ({len(rendered)} adapters)")
        return 0
    for path in stale:
        if path in rendered:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as fh:
                fh.write(rendered[path])
        else:
            path.unlink()
    print(f"Synced {len(stale)} file(s); {len(rendered)} adapters up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
